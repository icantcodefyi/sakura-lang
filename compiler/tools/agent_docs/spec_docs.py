"""Generate the fixture-indexed diagnostic table for the draft specification."""

import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "compiler/diagnostics"))
from check_history import parse

OUTPUT = "docs/spec/diagnostic-codes.md"
# Rule labels: G grammar, D diagnostics, and the semantics chapters' EV, TY, EF, ER, CC, MO.
RULE = re.compile(r"\*\*(?:G|D|EV|TY|EF|ER|CC|MO)\d+\*\*")
TEST_FIXTURES = {
    "D090": ("compiler/runtime/rt/tests/vt.rs", "malformed_values_are_d090_and_leak_nothing"),
    "D091": ("compiler/crates/sakura_cli/tests/wasm.rs", "serve_over_the_copy_budget_answers_413_or_500_and_keeps_serving"),
    "D092": ("compiler/runtime/rt/tests/exec.rs", "rc_overflow_is_d092"),
    "D093": ("compiler/runtime/rt/tests/exec.rs", "fail_escaping_a_finalizer_is_d093"),
    "D094": ("compiler/crates/sakura_lir/tests/defects.rs", "a_callback_outliving_its_perform_site_is_d094"),
    "D095": ("compiler/runtime/rt/tests/exec.rs", "fiber_self_reference"),
    "D096": ("compiler/runtime/rt/tests/heap.rs", "oom_is_one_defect_path_d096"),
    "V8002": ("compiler/crates/sakura_cli/tests/cli.rs", "reserved_package_names_are_v8002"),
    "V8003": ("compiler/runtime/js/test/wasm_host.test.js", "runMain and runTests report V8003 for another ABI and exit 2"),
    "V8004": ("compiler/crates/sakura_cli/tests/wasm.rs", "a_user_js_external_is_refused_on_wasm"),
    "V8020": ("compiler/crates/sakura_cli/tests/cli.rs", "frozen_specs_compare_with_git_head"),
    "V9001": ("compiler/crates/sakura_fmt/src/lib.rs", "guard_reports_a_dropped_comment_or_broken_output"),
    "W7002": ("compiler/crates/sakura_verify/tests/worker.rs", "records_keep_reasons_and_cross_check_disagreements"),
}


def render(root):
    entries = parse((root / "compiler/diagnostics/codes.txt").read_text())
    lines = [
        "# Diagnostic codes",
        "",
        "**Draft (normative at v1.0.0-beta.1).**",
        "",
        "Generated by `python3 compiler/tools/agent_docs/spec_docs.py`; do not edit.",
        "",
        "The identity, meaning label, and lifecycle status come from",
        "[the baseline](../../compiler/diagnostics/codes.txt).",
        "Severity is `error` for V codes, `warning` for W codes, and `defect` for D codes",
        "(a runtime category, not a diagnostic JSON severity).",
        "Fixture links identify checked-in evidence, not a claim that this generation ran it.",
        "Rows without an emission fixture are informative gaps; retired and reserved rows",
        "record identities, not requirements to emit a diagnostic.",
        "The [chapter](diagnostics.md) defines the table's scope.",
        "",
        "| Code | Severity/category | Meaning (identity label) | Fixture | Status |",
        "|---|---|---|---|---|",
    ]
    for code, (status, title) in sorted(entries.items()):
        candidates = sorted((root / "compiler/tests/ui").glob(f"{code}_*"))
        candidates = [p for p in candidates if (p.suffix == ".sak" and not p.name.endswith(".fixed.sak")) or p.is_dir()]
        candidates += sorted((root / "compiler/tests/semantics").glob(f"defect_{code}_*.sak"))
        fixtures = []
        for path in candidates:
            sources = sorted(path.glob("*.sak")) if path.is_dir() else [path]
            text = "\n".join(p.read_text(errors="replace") for p in sources)  # V0015 fixtures are not UTF-8 by design
            if re.search(r"//\s*skip:", text):
                continue
            milestone = re.search(r"//\s*milestone:\s*M(\d+)", text)
            if milestone and int(milestone[1]) > 3:
                continue
            if not re.search(rf"//\s*expect:\s*{code}\b", text) and not re.search(rf"//\s*expect-defect(?:@\w+)?:\s*{code}\b", text):
                continue
            fixtures = sources
            break
        test_name = None
        if not fixtures and code in TEST_FIXTURES:
            relative, test_name = TEST_FIXTURES[code]
            path = root / relative
            declared = rf"^\s*fn {test_name}\(" if path.suffix == ".rs" else rf'^test\("{re.escape(test_name)}"'
            if not path.is_file() or not re.search(declared, path.read_text(), re.MULTILINE):
                raise ValueError(f"missing indexed test: {relative}::{test_name}")
            fixtures = [path]
        evidence = ", ".join(f"[{test_name or p.name}](../../{p.relative_to(root).as_posix()})" for p in fixtures)
        if not evidence:
            evidence = "**Gap: no runnable emission fixture indexed**" if status == "active" else "Not emitted"
        severity = {"V": "error", "W": "warning", "D": "defect"}[code[0]]
        lines.append(f"| `{code}` | {severity} | `{title}` | {evidence} | {status} |")
    return "\n".join(lines) + "\n"


def check_links(root):
    errors = []
    rules = 0
    for path in sorted((root / "docs/spec").glob("*.md")):
        for number, line in enumerate(path.read_text().splitlines(), 1):
            links = re.findall(r"\[[^\]]*\]\(([^)]+)\)", line)
            for link in links:
                if "://" not in link and not link.startswith("#"):
                    target = (path.parent / link.split("#")[0]).resolve()
                    if not target.exists():
                        errors.append(f"{path.name}:{number}: broken link {link}")
            if RULE.match(line):
                rules += 1
                if not any(
                    "/tests/" in link or "/test/corpus/" in link or "/test_history.py" in link
                    or (link.endswith(".rs") and (path.parent / link).is_file()
                        and "#[test]" in (path.parent / link).read_text())
                    for link in links
                ):
                    errors.append(f"{path.name}:{number}: rule has no fixture")
    return rules, errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render(ROOT)
    path = ROOT / OUTPUT
    if args.check:
        rules, errors = check_links(ROOT)
        if not path.exists() or path.read_text() != expected:
            errors.append(f"{OUTPUT} is stale; run python3 compiler/tools/agent_docs/spec_docs.py")
        if errors:
            parser.exit(1, "\n".join(errors) + "\n")
        print(f"Spec table fresh; local file links valid; {rules}/{rules} labelled rules cite fixtures.")
    else:
        path.write_text(expected)


if __name__ == "__main__":
    main()
