//! CLI baseline generator, compiled inside the binary to inspect its private clap types.
use clap::CommandFactory;
use std::collections::BTreeSet;
use std::path::Path;

fn commands(command: &clap::Command, parent: &str, rows: &mut BTreeSet<String>) {
    let path = format!("{parent} {}", command.get_name()).trim().to_owned();
    rows.insert(format!("command {path} hidden={}", command.is_hide_set()));
    for arg in command.get_arguments() {
        let values: Vec<_> = arg
            .get_possible_values()
            .iter()
            .map(|v| v.get_name().to_owned())
            .collect();
        let defaults: Vec<_> = arg
            .get_default_values()
            .iter()
            .map(|v| v.to_string_lossy().into_owned())
            .collect();
        rows.insert(format!(
            "arg {path} {} short={:?} long={:?} aliases={:?} short_aliases={:?} action={:?} arity={:?} required={} hidden={} values={values:?} defaults={defaults:?}",
            arg.get_id(), arg.get_short(), arg.get_long(), arg.get_all_aliases(),
            arg.get_all_short_aliases(), arg.get_action(), arg.get_num_args(),
            arg.is_required_set(), arg.is_hide_set(),
        ));
    }
    for child in command.get_subcommands() {
        commands(child, &path, rows);
    }
}

fn environment(path: &Path, rows: &mut BTreeSet<String>) {
    if path.is_dir() {
        for entry in std::fs::read_dir(path).unwrap() {
            let path = entry.unwrap().path();
            if path
                .file_name()
                .is_some_and(|n| n == "tests" || n == "test")
            {
                continue;
            }
            environment(&path, rows);
        }
        return;
    }
    if !matches!(path.extension().and_then(|s| s.to_str()), Some("rs" | "js"))
        || path.to_string_lossy().ends_with(".test.js")
    {
        return;
    }
    let text = std::fs::read_to_string(path).unwrap();
    for prefix in [
        "var(\"",
        "var_os(\"",
        "env!(\"",
        "option_env!(\"",
        "bytesEnv(\"",
    ] {
        for tail in text.split(prefix).skip(1) {
            if let Some(name) = tail.split('"').next().filter(|n| n.starts_with("SAKURA_")) {
                rows.insert(format!("env {name}"));
            }
        }
    }
    for prefix in ["env.SAKURA_", "env?.SAKURA_"] {
        for tail in text.split(prefix).skip(1) {
            let name: String = tail
                .chars()
                .take_while(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || *c == '_')
                .collect();
            rows.insert(format!("env SAKURA_{name}"));
        }
    }
}

fn baseline() -> String {
    let mut rows = BTreeSet::new();
    let mut command = crate::Cli::command();
    command.build();
    commands(&command, "", &mut rows);
    let compiler = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    for entry in std::fs::read_dir(compiler.join("crates")).unwrap() {
        let src = entry.unwrap().path().join("src");
        if src.is_dir() {
            environment(&src, &mut rows);
        }
    }
    environment(&compiler.join("runtime"), &mut rows);
    for (name, code) in [
        ("success", 0),
        ("errors", crate::EXIT_ERRORS),
        ("usage", crate::EXIT_USAGE),
        ("test_failures", crate::EXIT_TEST_FAILURES),
        ("defect", crate::EXIT_DEFECT),
        ("permission", crate::EXIT_PERMISSION),
    ] {
        rows.insert(format!("exit {code} {name}"));
    }
    format!(
        "# Generated by cli_surface::regenerate; see compiler/contracts/README.md.\n{}\n",
        rows.into_iter().collect::<Vec<_>>().join("\n")
    )
}

#[test]
fn current_surface_matches_baseline() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../contracts/cli.txt");
    assert_eq!(
        std::fs::read_to_string(path).unwrap(),
        baseline(),
        "CLI surface drift: regenerate using compiler/contracts/README.md and review the diff"
    );
}

#[test]
#[ignore = "explicit baseline regeneration only"]
fn regenerate() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../contracts/cli.txt");
    std::fs::write(path, baseline()).unwrap();
}
