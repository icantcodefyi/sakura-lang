//! The error-code reference (design §17.144): one MDX page per entry of `codes::REGISTRY` under
//! `website/content/docs/errors/`, with the registry's explanation, the `compiler/tests/ui`
//! fixture as the wrong program and its `.fixed.sak` companion as the fixed one, plus an index
//! by phase and the section's `meta.json`. Every file in the directory is generated.

use std::path::Path;

use sakura_diagnostics::codes::{CodeInfo, REGISTRY};

pub const DIR: &str = "website/content/docs/errors";
const UI: &str = "compiler/tests/ui";
/// `UI_MILESTONE` of `sakura_cli/tests/common`: fixtures above it are not checked yet.
const UI_MILESTONE: u32 = 3;
/// A fixture longer than this (V0008's generated nesting) is linked, not inlined.
const MAX_INLINE: usize = 2_000;
/// A YAML comment, so neither the page nor its `.md` export shows it.
const HEADER: &str = "# Generated by `cargo run -p agent_docs` from the diagnostic registry and \
                      compiler/tests/ui; do not edit.";

/// The wrong program for a code: its file (or a directory fixture's files) and directives.
struct Fixture {
    rel: String,
    files: Vec<(String, String)>,
    command: Option<String>,
    skipped: Option<String>,
    fixed: Option<String>,
    jsonl: Option<String>,
    others: Vec<String>,
}

/// Every file of [`DIR`], as `(path relative to the repository, contents)`.
pub fn pages(root: &Path) -> Result<Vec<(String, String)>, String> {
    let ui = root.join(UI);
    let mut names: Vec<String> = std::fs::read_dir(&ui)
        .map_err(|e| format!("cannot read {UI}: {e}"))?
        .filter_map(|e| e.ok()?.file_name().into_string().ok())
        .collect();
    names.sort();
    let mut out = Vec::new();
    let mut fixed_count = 0;
    for info in REGISTRY {
        let fixture = fixture(&ui, &names, info.code.0)?;
        fixed_count += usize::from(fixture.as_ref().is_some_and(|f| f.fixed.is_some()));
        out.push((
            format!("{DIR}/{}.mdx", info.code.0),
            page(info, fixture.as_ref()),
        ));
    }
    out.push((format!("{DIR}/index.mdx"), index(fixed_count)));
    // Unlisted, `index` becomes the folder's own link in the sidebar.
    let pages: Vec<String> = REGISTRY
        .iter()
        .map(|i| format!("    \"{}\"", i.code.0))
        .collect();
    out.push((
        format!("{DIR}/meta.json"),
        format!(
            "{{\n  \"title\": \"Error codes\",\n  \"pages\": [\n{}\n  ]\n}}\n",
            pages.join(",\n")
        ),
    ));
    Ok(out)
}

/// The first `<code>_*.sak` fixture with a fixed companion, else the first one, else a
/// `<code>_*/` directory fixture.
fn fixture(ui: &Path, names: &[String], code: &str) -> Result<Option<Fixture>, String> {
    let prefix = format!("{code}_");
    let read = |name: &str| {
        std::fs::read_to_string(ui.join(name)).map_err(|e| format!("cannot read {UI}/{name}: {e}"))
    };
    let wrong: Vec<&String> = names
        .iter()
        .filter(|n| n.starts_with(&prefix) && n.ends_with(".sak") && !n.ends_with(".fixed.sak"))
        .collect();
    let fixed_of = |n: &str| format!("{}.fixed.sak", n.trim_end_matches(".sak"));
    let chosen = wrong
        .iter()
        .find(|n| names.contains(&fixed_of(n)))
        .or(wrong.first());
    let Some(name) = chosen else {
        let Some(dir) = names
            .iter()
            .find(|n| n.starts_with(&prefix) && ui.join(n).is_dir())
        else {
            return Ok(None);
        };
        let mut files: Vec<String> = std::fs::read_dir(ui.join(dir))
            .map_err(|e| format!("cannot read {UI}/{dir}: {e}"))?
            .filter_map(|e| e.ok()?.file_name().into_string().ok())
            .filter(|n| n.ends_with(".sak"))
            .collect();
        files.sort();
        let files = files
            .into_iter()
            .map(|f| Ok((f.clone(), read(&format!("{dir}/{f}"))?)))
            .collect::<Result<Vec<_>, String>>()?;
        return Ok(Some(described(
            format!("{dir}/"),
            files,
            None,
            None,
            vec![],
        )));
    };
    let text = read(name)?;
    let fixed = names
        .contains(&fixed_of(name))
        .then(|| read(&fixed_of(name)))
        .transpose()?;
    let jsonl_name = format!("{}.jsonl", name.trim_end_matches(".sak"));
    let jsonl = names
        .contains(&jsonl_name)
        .then(|| read(&jsonl_name))
        .transpose()?;
    let others = wrong
        .iter()
        .filter(|n| **n != *name)
        .map(|n| n.to_string())
        .collect();
    Ok(Some(described(
        name.to_string(),
        vec![(name.to_string(), text)],
        fixed,
        jsonl,
        others,
    )))
}

/// A fixture with its directives read from the first file's leading comments.
fn described(
    rel: String,
    files: Vec<(String, String)>,
    fixed: Option<String>,
    jsonl: Option<String>,
    others: Vec<String>,
) -> Fixture {
    let d = directives(&files[0].1);
    let get = |k: &str| {
        d.iter()
            .find(|(key, _)| *key == k)
            .map(|(_, v)| v.to_string())
    };
    let milestone = get("milestone")
        .and_then(|m| m.trim_start_matches('M').parse::<u32>().ok())
        .unwrap_or(0);
    Fixture {
        skipped: (milestone > UI_MILESTONE || rel.ends_with('/'))
            .then(|| get("needs").unwrap_or_else(|| format!("milestone M{milestone}"))),
        command: get("command"),
        rel,
        files,
        fixed,
        jsonl,
        others,
    }
}

/// A harness directive line (`// key: value`, as `common::directives` in `sakura_cli`'s tests).
fn directive(line: &str) -> Option<(&str, &str)> {
    let (k, v) = line.trim().strip_prefix("//")?.split_once(':')?;
    let k = k.trim();
    let valid = !k.is_empty()
        && k.bytes()
            .all(|b| b.is_ascii_lowercase() || b == b'-' || b == b'@');
    valid.then_some((k, v.trim()))
}

/// The directives among a fixture's leading comments.
fn directives(text: &str) -> Vec<(&str, &str)> {
    text.lines()
        .take_while(|l| l.trim().starts_with("//"))
        .filter_map(directive)
        .collect()
}

/// `text` without its directive lines and the blank lines they leave at the top.
fn without_directives(text: &str) -> String {
    let mut lines = text.lines().peekable();
    let mut kept = Vec::new();
    while let Some(l) = lines.next_if(|l| l.trim().starts_with("//")) {
        if directive(l).is_none() {
            kept.push(l);
        }
    }
    kept.extend(lines);
    kept.join("\n")
        .trim_start_matches('\n')
        .trim_end()
        .to_owned()
}

fn page(info: &CodeInfo, fixture: Option<&Fixture>) -> String {
    let code = info.code.0;
    let retired = info.explain.starts_with("Retired");
    let title = if retired {
        format!("{code} {} (retired)", info.title)
    } else {
        format!("{code} {}", info.title)
    };
    let kind = match (code.as_bytes()[0], info.phase) {
        (_, None) => "A runtime defect: the running program stops with it; no compile phase \
                      reports it, and `try` cannot catch it."
            .to_owned(),
        (b'W', Some(p)) => format!("A warning from the `{}` phase.", phase_name(p)),
        (_, Some(p)) => format!("An error from the `{}` phase.", phase_name(p)),
    };
    let mut out = format!(
        "---\n{HEADER}\ntitle: {}\ndescription: {}\n---\n\n{kind} `sakura explain {code}` \
         prints this explanation offline.\n\n{}\n",
        json(&title),
        json(&plain(&summary(info.explain))),
        explanation(info.explain),
    );
    if retired {
        out.push_str("\nRetired codes are never reported, so no program triggers this one.\n");
        return out;
    }
    if info.phase.is_none() {
        out.push_str(
            "\nRuntime defects come from running programs, so `compiler/tests/ui` has no \
             fixture for them; the explanation above names the repair.\n",
        );
        return out;
    }
    let repo = env!("CARGO_PKG_REPOSITORY");
    let link = |rel: &str| format!("[`{UI}/{rel}`]({repo}/blob/master/{UI}/{rel})");
    out.push_str("\n## Wrong program\n\n");
    let Some(f) = fixture else {
        out.push_str(&format!(
            "No fixture in `{UI}` reports this code yet.\n\n## Fixed program\n\n\
             No fixed program yet; the explanation above describes the repair.\n"
        ));
        return out;
    };
    let command = f.command.as_deref().unwrap_or("check");
    match &f.skipped {
        Some(needs) => out.push_str(&format!(
            "{}, which the compiler's ui suite does not run yet (needs: {}):\n",
            link(&f.rel),
            escape(needs)
        )),
        None => out.push_str(&format!(
            "{}, which the compiler's ui suite runs through `sakura {command}`:\n",
            link(&f.rel)
        )),
    }
    for (name, text) in &f.files {
        if f.files.len() > 1 {
            out.push_str(&format!("\n`{name}`:\n"));
        }
        let body = without_directives(text);
        if body.len() > MAX_INLINE {
            out.push_str(&format!(
                "\nThe program is {} bytes, too long to show here; open the file to read it.\n",
                body.len()
            ));
        } else {
            out.push_str(&format!("\n```sakura\n{body}\n```\n"));
        }
    }
    if f.skipped.is_none() {
        let record = f.jsonl.as_deref().and_then(|j| {
            j.lines()
                .filter_map(|l| serde_json::from_str::<serde_json::Value>(l).ok())
                .find(|r| r["code"] == code)
        });
        match record {
            Some(r) => out.push_str(&format!(
                "\n`sakura check --json` reports this record (pretty-printed; `$DIR` is the \
                 fixture's directory):\n\n```json\n{}\n```\n",
                serde_json::to_string_pretty(&r).unwrap()
            )),
            None => out.push_str(&format!("\n`sakura {command}` reports `{code}`.\n")),
        }
    }
    if !f.others.is_empty() {
        let others: Vec<String> = f.others.iter().map(|o| link(o)).collect();
        out.push_str(&format!(
            "\nMore fixtures for this code: {}.\n",
            others.join(", ")
        ));
    }
    out.push_str("\n## Fixed program\n\n");
    match &f.fixed {
        Some(fixed) => {
            let rel = format!("{}.fixed.sak", f.rel.trim_end_matches(".sak"));
            out.push_str(&format!(
                "{}, which `sakura {command}` accepts with no diagnostics:\n\n```sakura\n{}\n```\n",
                link(&rel),
                fixed.trim_end()
            ));
        }
        None => out.push_str(
            "No fixed program is checked in for this code yet; the explanation above describes \
             the repair.\n",
        ),
    }
    out
}

fn index(fixed_count: usize) -> String {
    let mut out = format!(
        "---\n{HEADER}\ntitle: Error codes\ndescription: {}\n---\n\n\
         Every diagnostic code the compiler and the runtime report, with its explanation, a \
         program that triggers it and, where one is checked in, the fixed program. Codes are \
         stable and never renumbered (design §12.3); `sakura explain <code>` prints the same \
         explanation offline, and a diagnostic's `explanation_uri` (`sakura://explain/<code>`) \
         maps to `/docs/errors/<code>`. `V` codes are errors, `W` warnings and `D` runtime \
         defects; the [diagnostics reference](/docs/agents/diagnostics) describes the JSON \
         records.\n\n{} codes; {fixed_count} pages show a fixed program that the compiler's \
         test suite checks.\n",
        json(
            "Every Sakura Lang diagnostic code with its explanation, a program that triggers \
             it and the fixed program."
        ),
        REGISTRY.len()
    );
    let mut group = "";
    for info in REGISTRY {
        let g = group_name(info);
        if g != group {
            out.push_str(&format!(
                "\n## {g}\n\n| Code | Title | Summary |\n| --- | --- | --- |\n"
            ));
            group = g;
        }
        let retired = if info.explain.starts_with("Retired") {
            " (retired)"
        } else {
            ""
        };
        out.push_str(&format!(
            "| [{0}](/docs/errors/{0}) | `{1}`{retired} | {2} |\n",
            info.code.0,
            info.title,
            escape(&summary(info.explain)).replace('|', "\\|")
        ));
    }
    out
}

fn group_name(info: &CodeInfo) -> &'static str {
    match info.code.0.as_bytes()[..2] {
        [b'W', _] => "Warnings",
        [b'D', _] => "Runtime defects",
        [_, b'0'] => "Lex and parse",
        [_, b'1'] => "Names and modules",
        [_, b'2'] => "Types",
        [_, b'3'] => "Effects and handlers",
        [_, b'4'] => "Patterns",
        [_, b'5'] => "Contracts and refinements",
        [_, b'6'] => "Capabilities, resources and escape",
        [_, b'7'] => "Tests and verification",
        [_, b'8'] => "Packages and build",
        _ => "Internal",
    }
}

fn phase_name(p: sakura_diagnostics::Phase) -> String {
    serde_json::to_value(p)
        .unwrap()
        .as_str()
        .unwrap()
        .to_owned()
}

/// The explanation's first sentence, on one line.
fn summary(explain: &str) -> String {
    let para = explain.split("\n\n").next().unwrap_or("");
    let line = para.split_whitespace().collect::<Vec<_>>().join(" ");
    match line.find(". ") {
        Some(i) => line[..=i].to_owned(),
        None => line,
    }
}

/// `text` as a YAML scalar (a JSON string is one).
fn json(text: &str) -> String {
    serde_json::to_string(text).unwrap()
}

/// `text` without Markdown code markers, for metadata.
fn plain(text: &str) -> String {
    text.replace('`', "")
}

/// The registry's plain-text explanation as MDX: four-space-indented blocks become fenced code
/// (`toml` when they start with a `[table]`), prose is escaped outside inline code.
fn explanation(explain: &str) -> String {
    let mut out = String::new();
    let mut block: Vec<&str> = Vec::new();
    let flush = |block: &mut Vec<&str>, out: &mut String| {
        if block.is_empty() {
            return;
        }
        let lang = if block[0].starts_with('[') {
            "toml"
        } else {
            "sakura"
        };
        out.push_str(&format!("\n```{lang}\n{}\n```\n\n", block.join("\n")));
        block.clear();
    };
    for line in explain.lines() {
        match line.strip_prefix("    ") {
            Some(code) => block.push(code),
            None => {
                flush(&mut block, &mut out);
                out.push_str(&escape(line));
                out.push('\n');
            }
        }
    }
    flush(&mut block, &mut out);
    out.trim_end().replace("\n\n\n", "\n\n")
}

/// Escapes MDX's expression and JSX openers outside inline code spans.
fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut in_code = false;
    for c in text.chars() {
        if c == '`' {
            in_code = !in_code;
        }
        if !in_code && matches!(c, '{' | '}' | '<' | '>' | '*') {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn explanations_become_mdx() {
        let md = explanation(
            "Use `{x}` not {x} or a < b.\n\nWrong:\n    let a = {}\nFixed:\n    [package]",
        );
        assert_eq!(
            md,
            "Use `{x}` not \\{x\\} or a \\< b.\n\nWrong:\n\n```sakura\nlet a = {}\n```\n\nFixed:\n\n```toml\n[package]\n```"
        );
    }

    #[test]
    fn directives_are_dropped_and_comments_kept() {
        let text =
            "// milestone: M1\n// expect: V0007\n// `spawn` is reserved: see §2.1.\nfn f() {}\n";
        assert_eq!(
            without_directives(text),
            "// `spawn` is reserved: see §2.1.\nfn f() {}"
        );
        assert_eq!(directives(text), [("milestone", "M1"), ("expect", "V0007")]);
    }
}
