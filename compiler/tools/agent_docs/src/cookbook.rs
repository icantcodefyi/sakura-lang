//! Cookbook pages and the portable reference, extracted from the executable example projects.

use std::path::Path;

const RECIPES: &[&str] = &[
    "json_refined",
    "cli_files",
    "http_retry",
    "sqlite_query",
    "router_endpoint",
    "scripted_tool",
    "budgeted_agent",
    "indexed_update",
    "url_build",
    "form_upload",
    "sign_webhook",
];
const NOTICE: &str = "Generated by `cargo run -p agent_docs` from `compiler/examples/`. Edit the example files, then regenerate.";
const SOURCE_URL: &str = "https://github.com/icantcodefyi/sakuralang/tree/main/compiler/examples";

fn read(path: &Path) -> Result<String, String> {
    std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))
}

pub fn outputs(root: &Path) -> Result<Vec<(String, String)>, String> {
    let examples = root.join("compiler/examples");
    let intro = read(&examples.join("cookbook.md"))?;
    // A recipe page repeats only the intro's opening paragraphs; its sections are the index's.
    let provenance = intro.split("\n## ").next().unwrap_or(&intro);
    let mut index = format!(
        "---\ntitle: Cookbook\ndescription: Ten small, tested Sakura projects that run offline.\n---\n\n{NOTICE}\n\n{intro}\n"
    );
    let mut skill = format!("# Sakura cookbook\n\n{NOTICE}\n\n{intro}");
    let mut out = Vec::new();
    for &name in RECIPES {
        let dir = examples.join(name);
        let guide = read(&dir.join("recipe.md"))?;
        let (title, prose) = guide
            .strip_prefix("# ")
            .and_then(|s| s.split_once('\n'))
            .ok_or_else(|| format!("{name}/recipe.md needs a level-one title"))?;
        let description = prose.trim().lines().next().unwrap_or("");
        let source = read(&dir.join("src/main.sak"))?;
        let header: Vec<_> = source.lines().take_while(|l| l.starts_with("//")).collect();
        if !header.contains(&"// milestone: M3")
            || !header
                .iter()
                .any(|l| matches!(*l, "// mode: run" | "// mode: test"))
            || header.iter().any(|l| l.starts_with("// known-bug:"))
            || !source.lines().any(|l| l.starts_with("test \""))
        {
            return Err(format!(
                "{name} must be an unskipped M3 run/test project with tests"
            ));
        }
        let shown = agent_docs::without_directives(&source);
        let manifest = read(&dir.join("sakura.toml"))?;
        let run = header.contains(&"// mode: run");
        let args = header.iter().find_map(|l| l.strip_prefix("// args: "));
        let command = match (run, args) {
            (true, Some(args)) => format!("sakura run -- {args}\n"),
            (true, None) => "sakura run\n".into(),
            (false, _) => String::new(),
        };
        let mut body = format!(
            "{}\n\n[Source project]({SOURCE_URL}/{name}) · harness mode: `{}`.\n\n\
             From the repository root, with this checkout's `sakura` on `PATH`:\n\n\
             ```sh\ncd compiler/examples/{name}\nsakura check --json\n{command}sakura test --json\n```\n\n\
             ### Manifest and permissions\n\n```toml\n{manifest}```\n\n\
             ### Source and tests\n\n`src/main.sak` includes all required imports and tests.\n\n\
             ```sakura test id=cookbook-{name} project={name}\n{shown}```\n",
            prose.trim(),
            if run { "run + test" } else { "test" },
        );
        if run {
            let stdout = read(&dir.join("expected.stdout"))?;
            body.push_str(&format!("\n### Expected stdout\n\n```text\n{stdout}```\n"));
        }
        for folder in ["data", "tests/fixtures"] {
            for (rel, text) in files(&dir, folder)? {
                let language = if rel.ends_with(".jsonl") {
                    "jsonl"
                } else {
                    "text"
                };
                body.push_str(&format!("\n### `{rel}`\n\n```{language}\n{text}```\n"));
            }
        }
        index.push_str(&format!(
            "- [{title}](/docs/cookbook/{name}) — {description}\n"
        ));
        skill.push_str(&format!("\n## {title}\n\n{body}"));
        out.push((
            format!("website/content/docs/cookbook/{name}.mdx"),
            format!(
                "---\ntitle: {}\ndescription: {}\n---\n\n{NOTICE}\n\n{body}\n### Compiler provenance and regeneration\n\n{provenance}",
                serde_json::to_string(title).unwrap(),
                serde_json::to_string(description).unwrap(),
            ),
        ));
    }
    let pages: Vec<_> = std::iter::once("index")
        .chain(RECIPES.iter().copied())
        .collect();
    let meta = serde_json::json!({"title": "Cookbook", "pages": pages});
    out.push(("website/content/docs/cookbook/index.mdx".into(), index));
    out.push((
        "website/content/docs/cookbook/meta.json".into(),
        format!("{}\n", serde_json::to_string_pretty(&meta).unwrap()),
    ));
    out.push(("skills/sakura/references/recipes.md".into(), skill));
    // A removed or renamed recipe must not leave a stale page in the searchable cookbook.
    if let Ok(entries) = std::fs::read_dir(root.join("website/content/docs/cookbook")) {
        for entry in entries {
            let path = entry.map_err(|e| e.to_string())?.path();
            if path.extension().is_some_and(|ext| ext == "mdx") {
                let name = path.file_stem().unwrap().to_string_lossy();
                if name != "index" && !RECIPES.contains(&name.as_ref()) {
                    return Err(format!(
                        "orphan cookbook page {}; remove it",
                        path.display()
                    ));
                }
            }
        }
    }
    Ok(out)
}

/// Only project data and fixtures, never generated build artifacts.
fn files(project: &Path, relative: &str) -> Result<Vec<(String, String)>, String> {
    let dir = project.join(relative);
    if !dir.exists() {
        return Ok(Vec::new());
    }
    let mut entries = std::fs::read_dir(&dir)
        .map_err(|e| format!("{}: {e}", dir.display()))?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|e| e.to_string())?;
    entries.sort_by_key(|e| e.file_name());
    let mut out = Vec::new();
    for entry in entries {
        let path = entry.path();
        let rel = format!("{relative}/{}", entry.file_name().to_string_lossy());
        if path.is_dir() {
            out.extend(files(project, &rel)?);
        } else {
            let text = read(&path)?;
            if !text.ends_with('\n') || text.contains("```") {
                return Err(format!(
                    "{} needs a trailing newline and no fence delimiters",
                    path.display()
                ));
            }
            out.push((rel, text));
        }
    }
    Ok(out)
}
