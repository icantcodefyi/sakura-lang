//! `cargo run -p agent_docs [-- --check]`: writes the agent-facing references from the compiler's
//! own sources (design §17.142): the `sakura` skill's `references/` and the signature listing of
//! `compiler/std/INDEX.md`. `--check` writes nothing and exits 1 when any output is stale.

use std::path::{Path, PathBuf};
use std::process::ExitCode;

use sakura_analysis::{Analysis, Snapshot, Symbol, std_sources};
use sakura_diagnostics::codes::REGISTRY;

/// INDEX.md's generated listing sits between these lines; the prose around it is authored.
const BEGIN: &str =
    "<!-- agent_docs: signatures begin (generated by `cargo run -p agent_docs`; do not edit) -->";
const END: &str = "<!-- agent_docs: signatures end -->";

fn repo() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..")
}

fn main() -> ExitCode {
    let check = match std::env::args().nth(1).as_deref() {
        None => false,
        Some("--check") => true,
        Some(other) => {
            eprintln!("usage: agent_docs [--check] (unknown argument `{other}`)");
            return ExitCode::from(2);
        }
    };
    let root = repo();
    let outputs = match outputs(&root) {
        Ok(o) => o,
        Err(e) => {
            eprintln!("agent_docs: {e}");
            return ExitCode::FAILURE;
        }
    };
    let mut stale = Vec::new();
    for (rel, text) in outputs {
        let path = root.join(rel);
        if std::fs::read_to_string(&path).ok().as_deref() == Some(text.as_str()) {
            continue;
        }
        if check {
            stale.push(rel);
        } else {
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(&path, text).unwrap();
            eprintln!("wrote {rel}");
        }
    }
    if stale.is_empty() {
        return ExitCode::SUCCESS;
    }
    eprintln!(
        "stale: {}\nrun `cargo run -p agent_docs` in compiler/ and commit the result",
        stale.join(", ")
    );
    ExitCode::FAILURE
}

/// Every generated file, as `(path relative to the repository, contents)`.
fn outputs(root: &Path) -> Result<Vec<(&'static str, String)>, String> {
    let read = |rel: &str| {
        std::fs::read_to_string(root.join(rel)).map_err(|e| format!("cannot read {rel}: {e}"))
    };
    let listing = std_signatures();
    if listing.is_empty() {
        return Err("the embedded std is empty; rebuild sakura_analysis".into());
    }
    let index = with_signatures(&read("compiler/std/INDEX.md")?, &listing)?;
    Ok(vec![
        (
            "skills/sakura/references/language.md",
            read("docs/llms.txt")?,
        ),
        ("skills/sakura/references/stdlib.md", index.clone()),
        ("skills/sakura/references/diagnostics.md", diagnostics()),
        ("compiler/std/INDEX.md", index),
    ])
}

/// `index` with the text between [`BEGIN`] and [`END`] replaced by `listing`.
fn with_signatures(index: &str, listing: &str) -> Result<String, String> {
    let (head, rest) = index
        .split_once(BEGIN)
        .ok_or("compiler/std/INDEX.md has no begin marker")?;
    let (_, tail) = rest
        .split_once(END)
        .ok_or("compiler/std/INDEX.md has no end marker")?;
    Ok(format!("{head}{BEGIN}\n\n{listing}\n{END}{tail}"))
}

/// One `### \`std/<module>\`` section per module, modules in path order, each module's public
/// items in source order with their contracts and attributes.
fn std_signatures() -> String {
    let sources: Vec<(String, String)> = std_sources().collect();
    let a = Analysis::analyze(&Snapshot::new(sources.clone()));
    let text_of = |uri: &str| {
        sources
            .iter()
            .find(|(u, _)| u == uri)
            .map_or("", |(_, t)| t.as_str())
    };
    let mut items: Vec<&Symbol> = a
        .symbols()
        .iter()
        .filter(|s| s.is_pub && matches!(s.kind, "fn" | "const" | "type" | "error" | "effect"))
        .collect();
    items.sort_by(|x, y| (&x.module, x.item_range[0]).cmp(&(&y.module, y.item_range[0])));
    let mut out = String::new();
    let mut module = None;
    for s in items {
        if module != Some(&s.module) {
            if module.is_some() {
                out.push_str("```\n\n");
            }
            out.push_str(&format!("### `std/{}`\n\n```sakura fragment\n", s.module));
            module = Some(&s.module);
        }
        if s.kind == "effect" {
            out.push_str(&format!("effect {} {{\n", s.name));
            let prefix = format!("{}.", s.id);
            for op in a
                .symbols()
                .iter()
                .filter(|o| o.kind == "op" && o.id.starts_with(&prefix))
            {
                out.push_str(&format!("  {}\n", line(op, "")));
            }
            out.push_str("}\n");
        } else {
            let item = &text_of(&s.uri)[s.item_range[0] as usize..s.item_range[1] as usize];
            out.push_str(&format!("{}\n", line(s, item)));
        }
    }
    if module.is_some() {
        out.push_str("```\n");
    }
    out
}

/// A declaration on one line, without `pub`, followed by its contracts and a comment naming its
/// attributes (`@external`, `@total`, …) found in its item text.
fn line(s: &Symbol, item: &str) -> String {
    let sig = s.signature.strip_prefix("pub ").unwrap_or(&s.signature);
    let mut out = std::iter::once(sig)
        // A type's `where` is already part of its signature.
        .chain(
            s.contracts
                .iter()
                .map(String::as_str)
                .filter(|c| !sig.contains(c)),
        )
        .collect::<Vec<_>>()
        .join(" ");
    let attrs: Vec<&str> = item
        .lines()
        .map(str::trim)
        .filter_map(|l| l.strip_prefix('@'))
        .map(|l| {
            &l[..l
                .find(|c: char| !c.is_ascii_alphanumeric() && c != '_')
                .unwrap_or(l.len())]
        })
        .collect();
    if !attrs.is_empty() {
        out.push_str(&format!("    // @{}", attrs.join(", @")));
    }
    out
}

/// Every registered code with its title, phase and `sakura explain` text.
fn diagnostics() -> String {
    let mut out = format!(
        "# Sakura Lang diagnostics\n\n\
         Generated by `cargo run -p agent_docs` from the compiler's diagnostic registry; \
         `sakura explain <code>` prints the same text. {} codes. `V` codes are compile-time \
         errors, `W` warnings, `D` runtime defects. Codes are stable and never renumbered.\n",
        REGISTRY.len()
    );
    for info in REGISTRY {
        let phase = info.phase.map_or("runtime defect".to_owned(), |p| {
            serde_json::to_value(p)
                .unwrap()
                .as_str()
                .unwrap()
                .to_owned()
        });
        out.push_str(&format!(
            "\n## {} `{}` ({phase})\n\n```text\n{}\n```\n",
            info.code.0, info.title, info.explain
        ));
    }
    out
}

#[cfg(test)]
mod tests {
    #[test]
    fn outputs_are_fresh() {
        let root = super::repo();
        for (rel, text) in super::outputs(&root).unwrap() {
            let on_disk = std::fs::read_to_string(root.join(rel)).unwrap_or_default();
            assert!(
                on_disk == text,
                "{rel} is stale: run `cargo run -p agent_docs` in compiler/ and commit it"
            );
        }
    }
}
