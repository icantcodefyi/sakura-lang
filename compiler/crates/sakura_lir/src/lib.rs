//! Sakura Lang's low-level IR for the WASM backend (design §17.82, §17.83; plan §3.5 M4-LIR).
//!
//! Input is Core, read through the shared snapshot form `sakura-core-snapshot-v1` (§17.107):
//! [`from_core`] converts live `sakura_core` Core and lowers it; [`lower::lower`] takes a
//! committed snapshot. Output is [`lir::Module`], checked by [`validate`] and run by
//! `sakura_eval::lir`.

pub mod debug;
pub mod direct;
pub mod image;
pub mod layout;
pub mod lir;
pub mod lower;
pub mod print;
pub mod schema;
pub mod validate;

use std::collections::BTreeMap;

/// `sakura-core-snapshot-v1` (§17.107), the shared committed Core.
pub use sakura_core_snapshot as snapshot;

/// Each runtime builtin's parameter and result representations, and whether it calls back
/// (`src/builtins.sigs`, generated by `examples/regen_core.rs` from std's `@external`
/// declarations).
pub const BUILTIN_SIGS: &str = include_str!("builtins.sigs");

/// [`BUILTIN_SIGS`], parsed.
pub fn builtin_sigs() -> BTreeMap<String, (lir::Sig, bool)> {
    lower::parse_sigs(BUILTIN_SIGS).expect("src/builtins.sigs is generated and well formed")
}

/// How `Option` is represented (design §17.83, §17.99; `--layout`).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Layout {
    /// A tagged variant like any other: the default.
    #[default]
    Tagged,
    /// `None = 0`, `Some(p) = p` (ABI §4.3). M4-OPT's; off until the nested-option corpus
    /// passes on both layouts, so lowering refuses it.
    Niche,
}

/// Lowers live Core to LIR.
pub fn from_core(core: &sakura_core::Module, layout: Layout) -> Result<lir::Module, String> {
    if layout == Layout::Niche {
        return Err("`--layout=niche` is not implemented yet (M4-OPT, design §17.99)".into());
    }
    lower::lower(&snapshot::convert::convert(core), &builtin_sigs())
}
