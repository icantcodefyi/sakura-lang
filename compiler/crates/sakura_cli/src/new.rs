//! `sakura new <kind> <name>` and `sakura init`: a project with `sakura.toml`, `sakura.lock`,
//! `src/main.sak` with one test, a `[permissions]` table, and `AGENTS.md` and `CLAUDE.md`
//! (`@AGENTS.md`) for coding agents (design §12.1, §17.143).

use std::path::Path;
use std::process::ExitCode;

use crate::{asset, setup, usage_error};

const CLI: &str = r#"import std/cli.{Cli}

/// The greeting for `name`.
pub fn greeting(name: String) -> String { "hello, {name}" }

pub fn main() -> Unit ! {Cli, Console} {
  let name = Option.unwrap_or(List.first(Cli.args()), "world")
  Console.print(greeting(name))
}

test "greets by name" { expect_eq(greeting("Sakura Lang"), "hello, Sakura Lang") }
"#;

const LIB: &str = r#"/// `x` limited to `lo..=hi`.
pub fn clamp(x: Int, lo: Int, hi: Int) -> Int
  requires ordered: lo <= hi
{ if x < lo { lo } else if x > hi { hi } else { x } }

test "clamps to the bounds" {
  expect_eq(clamp(5, 0, 3), 3)
  expect_eq(clamp(-1, 0, 3), 0)
}
"#;

const AGENT: &str = r#"import std/budget.{Budget, Limits}
import std/http.{Http}
import std/llm.{Llm, LlmError, Model}

type Answer = { text: String where String.len(it) > 0 }

@llm(system: "Answer in one short sentence.")
fn answer(question: Untrusted<String>) -> Answer ! {Llm, Fail<LlmError>}

pub fn main() -> Unit ! {Console, Env, Http, Fail<LlmError>} {
  let key = Env.secret("ANTHROPIC_API_KEY").expect("set ANTHROPIC_API_KEY")
  let limits = Limits { tokens: Some(10_000), usd: Some(0.10), calls: None }
  with Budget.limits(limits), Llm.anthropic(key, Model.of("claude-sonnet-5-5")) {
    Console.print(answer(Untrusted.of("What is a typed hole?")).text)
  }
}

test "the scripted answer is validated" {
  with Llm.scripted([Json.encode(Answer { text: "A placeholder." })]) {
    let text = try { answer(Untrusted.of("anything")).text } catch {
      _ => "no answer",
    }
    expect_eq(text, "A placeholder.")
  }
}
"#;

const API: &str = r#"import std/request.{Get, Request}
import std/response.{Response, Status}
import std/router.{Router}
import std/serve.{Address, Serve, ServeError}
import std/url.{Url}

/// The routes of this service; `{}`: its handlers perform no effects.
pub fn routes() -> Router<{}> {
  Router.new().get("/health", fn(_req) { Response.status(200, "ok") })
}

pub fn main() -> Unit ! {Serve, Fail<ServeError>} {
  Serve.listen(routes(), Address.of("127.0.0.1", 8080))
}

test "health answers 200" {
  expect_eq(Router.handle(routes(), Request.of(Get, Url.from("/health"))).status, Status.from(200))
}
"#;

const LOCK: &str = "# Generated by sakura: exact versions and content hashes of dependencies.\n\
                    version = 1\n";

/// `src/main.sak` and the `[permissions]` lines of a project kind.
fn template(kind: &str) -> Result<(&'static str, &'static str), String> {
    Ok(match kind {
        "cli" => (CLI, ""),
        "lib" => (LIB, ""),
        "agent" => (
            AGENT,
            "net = [\"api.anthropic.com:443\"]\nenv = [\"ANTHROPIC_API_KEY\"]\n",
        ),
        "api" => (API, "net = [\"127.0.0.1:8080\"]\n"),
        _ => {
            return Err(format!(
                "unknown project kind `{kind}`; use cli, lib, agent or api"
            ));
        }
    })
}

/// Creates `dir` (which must be empty or absent) as a `kind` project named `name`, then runs
/// `sakura setup --apply` in it for `setup_client`, if given.
pub fn new(kind: &str, name: &str, dir: &Path, setup_client: Option<&str>) -> ExitCode {
    if dir.read_dir().is_ok_and(|mut d| d.next().is_some()) {
        return usage_error(format!("{} exists and is not empty", dir.display()));
    }
    match (scaffold(kind, name, dir), setup_client) {
        (code, Some(client)) if code == ExitCode::SUCCESS => setup::setup_in(dir, client, true),
        (code, _) => code,
    }
}

/// Makes the current directory a `kind` project named after it. Existing files are kept.
pub fn init(kind: &str) -> ExitCode {
    let cwd = std::env::current_dir().unwrap_or_default();
    let name = cwd
        .file_name()
        .map(|n| n.to_string_lossy().to_lowercase().replace('-', "_"))
        .unwrap_or_default();
    scaffold(kind, &name, &cwd)
}

fn scaffold(kind: &str, name: &str, dir: &Path) -> ExitCode {
    let valid = name.starts_with(|c: char| c.is_ascii_lowercase())
        && name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
    if !valid {
        return usage_error(format!(
            "`{name}` is not a package name: use lowercase letters, digits and `_`"
        ));
    }
    let (main, permissions) = match template(kind) {
        Ok(t) => t,
        Err(e) => return usage_error(e),
    };
    if dir.join("sakura.toml").exists() {
        return usage_error(format!("{} already has a sakura.toml", dir.display()));
    }
    let manifest = format!(
        "[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2026\"\n\n\
         # Root authority `main` gets; everything absent is denied (design §6.2).\n\
         [permissions]\n{permissions}"
    );
    let files = [
        ("sakura.toml", manifest.as_str()),
        ("sakura.lock", LOCK),
        ("src/main.sak", main),
        (".gitignore", "/target/\n"),
        // Sources LF in every checkout, so `fmt --check` holds on Windows; snapshots exactly as
        // the runner wrote them, `\r` included (§17.180 (4b), §17.196 (1)).
        (".gitattributes", "*.sak text eol=lf\n*.snap -text\n"),
        ("AGENTS.md", asset("AGENTS.md")),
        ("CLAUDE.md", asset("CLAUDE.md")),
    ];
    for (rel, text) in files {
        let path = dir.join(rel);
        if path.exists() {
            eprintln!("kept {}", path.display());
            continue;
        }
        let written = path
            .parent()
            .map_or(Ok(()), std::fs::create_dir_all)
            .and_then(|()| std::fs::write(&path, text));
        if let Err(e) = written {
            return usage_error(format!("{}: {e}", path.display()));
        }
        if rel == "sakura.toml" {
            // The name `init` derives from the directory is otherwise only in the file.
            eprintln!("created {} (package `{name}`)", path.display());
        } else {
            eprintln!("created {}", path.display());
        }
    }
    ExitCode::SUCCESS
}
