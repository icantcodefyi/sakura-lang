//! `sakura.lock` (RFC 0003 §3, experimental): `version = 2` TOML listing every package of the
//! build, read by every compiler command and never resolved or fetched by them. `version = 1`
//! (what `sakura new` wrote before packages) reads as a lock without packages. Also the walk over
//! `path` dependencies ([`Graph`]) that both the lock this release writes for a path-only project
//! and the staleness check (`V8031`) are made from.

use std::collections::BTreeMap;
use std::ops::Range;

use serde::Deserialize as _;

use crate::manifest::{Dependency, DependencySource, Manifest, relative_path};

/// The first line of every lock `sakura` writes.
pub const HEADER: &str =
    "# Generated by sakura: exact versions and content hashes of dependencies.\n";

/// At most this many packages in one build (RFC 0003 §4.5).
pub const MAX_PACKAGES: usize = 1024;

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Lock {
    /// Sorted by name, one per name.
    pub packages: Vec<LockedPackage>,
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct LockedPackage {
    pub name: String,
    pub version: String,
    /// `path+<dir relative to the root>`, `registry+<url>` or `git+<url>#<rev>`.
    pub source: String,
    /// `sha256:<hex>` of the canonical tarball; `None` for a `path` source.
    pub checksum: Option<String>,
    /// The package's declared ceiling, `[]` without one.
    pub effects: Vec<String>,
    /// Whether the package may acquire authority (`V6020`).
    pub trusted: bool,
    /// `"<name> <version>"` of each direct dependency, sorted.
    pub dependencies: Vec<String>,
    /// The `[[package]]` table in the lock's text (`0..0` for a lock not read from text).
    pub span: Range<usize>,
}

impl LockedPackage {
    /// The directory of a `path` source, relative to the root package's.
    pub fn path(&self) -> Option<&str> {
        self.source.strip_prefix("path+")
    }
}

/// Why a lock's text is not a lock (`V8031`), at the offending range.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LockError {
    pub message: String,
    pub span: Range<usize>,
}

#[derive(serde::Deserialize)]
#[serde(deny_unknown_fields)]
struct Entry {
    name: String,
    version: String,
    source: String,
    checksum: Option<String>,
    #[serde(default)]
    effects: Vec<String>,
    #[serde(default)]
    trusted: bool,
    #[serde(default)]
    dependencies: Vec<String>,
}

#[derive(serde::Deserialize)]
#[serde(deny_unknown_fields)]
struct File {
    #[serde(default)]
    package: Vec<toml::Spanned<Entry>>,
}

impl Lock {
    /// Reads a lock: `version = 1` is a lock without packages; `version = 2` is RFC 0003 §3.1's.
    pub fn parse(text: &str) -> Result<Lock, LockError> {
        let invalid = |e: toml::de::Error| LockError {
            message: format!(
                "sakura.lock is not a valid lock: {}",
                e.message().trim_end()
            ),
            span: e.span().unwrap_or(0..0),
        };
        let mut table = toml::de::DeTable::parse(text).map_err(invalid)?;
        let version = table.get_mut().remove("version");
        let (version, at) = match version.as_ref().map(|v| (v.get_ref(), v.span())) {
            Some((toml::de::DeValue::Integer(i), at)) => (i.as_str().parse::<u64>().ok(), at),
            Some((_, at)) => (None, at),
            None => (None, 0..0),
        };
        match version {
            Some(1) => return Ok(Lock::default()),
            Some(2) => {}
            _ => {
                return Err(LockError {
                    message: "sakura.lock must say `version = 1` or `version = 2`".to_owned(),
                    span: at,
                });
            }
        }
        let file = File::deserialize(toml::de::Deserializer::from(table)).map_err(invalid)?;
        let mut lock = Lock::default();
        for e in file.package {
            // From the `[[package]]` header to the end of its table.
            let start = e.span().start;
            let end = (text[start + 1..].find("\n["))
                .map_or(text.len(), |i| start + 1 + i)
                .max(e.span().end);
            let span = start..start + text[start..end].trim_end().len();
            let e = e.into_inner();
            if lock.get(&e.name).is_some() {
                return Err(LockError {
                    message: format!("sakura.lock lists `{}` twice", e.name),
                    span,
                });
            }
            lock.packages.push(LockedPackage {
                name: e.name,
                version: e.version,
                source: e.source,
                checksum: e.checksum,
                effects: e.effects,
                trusted: e.trusted,
                dependencies: e.dependencies,
                span,
            });
        }
        lock.packages.sort_by(|a, b| a.name.cmp(&b.name));
        Ok(lock)
    }

    /// The `version = 2` text of the lock, byte for byte the same for the same packages.
    pub fn render(&self) -> String {
        use std::fmt::Write;
        let s = |v: &str| toml::Value::String(v.to_owned()).to_string();
        let list = |vs: &[String]| {
            let items: Vec<String> = vs.iter().map(|v| s(v)).collect();
            format!("[{}]", items.join(", "))
        };
        let mut out = format!("{HEADER}version = 2\n");
        let mut packages: Vec<&LockedPackage> = self.packages.iter().collect();
        packages.sort_by(|a, b| a.name.cmp(&b.name));
        for p in packages {
            let _ = write!(
                out,
                "\n[[package]]\nname = {}\nversion = {}\nsource = {}\n",
                s(&p.name),
                s(&p.version),
                s(&p.source)
            );
            if let Some(c) = &p.checksum {
                let _ = writeln!(out, "checksum = {}", s(c));
            }
            let _ = writeln!(out, "effects = {}", list(&p.effects));
            let _ = writeln!(out, "trusted = {}", p.trusted);
            let _ = writeln!(out, "dependencies = {}", list(&p.dependencies));
        }
        out
    }

    pub fn get(&self, name: &str) -> Option<&LockedPackage> {
        self.packages.iter().find(|p| p.name == name)
    }
}

/// One package reached from the root through `path` entries: its directory relative to the
/// root's (`""` for the root) and its manifest, with `M` whatever the caller keeps beside it.
#[derive(Clone, Debug)]
pub struct Node<M> {
    pub dir: String,
    pub manifest: Manifest,
    pub meta: M,
}

/// Why a walk stopped short of a `path` entry.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum WalkProblem {
    /// No `sakura.toml` in the directory `dir` the entry names.
    Missing { dir: String },
    /// The directory's manifest names another package than the entry's key.
    Renamed { found: String },
    /// The entry names the root package's own directory.
    Cycle,
}

/// The packages reachable from a root manifest through `path` entries (RFC 0003 §2): breadth
/// first, so each package is reached first along a shortest chain, and at most
/// [`MAX_PACKAGES`].
#[derive(Clone, Debug)]
pub struct Graph<M> {
    /// The root first.
    pub nodes: Vec<Node<M>>,
    /// Per node, per entry of its `[dependencies]` (in order): the node it reaches, or why not
    /// (`Err(None)` for an entry that is not a `path` entry, or past [`MAX_PACKAGES`]).
    pub edges: Vec<Vec<Result<usize, Option<WalkProblem>>>>,
    /// The walk stopped at [`MAX_PACKAGES`].
    pub truncated: bool,
}

impl<M> Graph<M> {
    /// Walks from `root`; `find(dir)` is the manifest in `dir` (relative to the root's
    /// directory), if there is one.
    pub fn walk(root: Node<M>, find: &mut dyn FnMut(&str) -> Option<(Manifest, M)>) -> Graph<M> {
        let mut g = Graph {
            nodes: vec![root],
            edges: Vec::new(),
            truncated: false,
        };
        let mut by_dir: BTreeMap<String, usize> = BTreeMap::from([(String::new(), 0)]);
        let mut i = 0;
        while i < g.nodes.len() {
            let mut edges = Vec::new();
            let deps = g.nodes[i].manifest.dependencies.clone();
            for d in &deps {
                let DependencySource::Path(p) = &d.source else {
                    edges.push(Err(None));
                    continue;
                };
                let Some(dir) = join(&g.nodes[i].dir, p) else {
                    edges.push(Err(Some(WalkProblem::Cycle)));
                    continue;
                };
                if let Some(&n) = by_dir.get(&dir) {
                    edges.push(check_name(&g.nodes[n].manifest, d).map(|()| n));
                    continue;
                }
                if g.nodes.len() == MAX_PACKAGES {
                    g.truncated = true;
                    edges.push(Err(None));
                    continue;
                }
                let Some((manifest, meta)) = find(&dir) else {
                    edges.push(Err(Some(WalkProblem::Missing { dir })));
                    continue;
                };
                if let Err(e) = check_name(&manifest, d) {
                    edges.push(Err(e));
                    continue;
                }
                by_dir.insert(dir.clone(), g.nodes.len());
                edges.push(Ok(g.nodes.len()));
                g.nodes.push(Node {
                    dir,
                    manifest,
                    meta,
                });
            }
            g.edges.push(edges);
            i += 1;
        }
        g
    }

    /// Whether each node may acquire authority: the root's own entries say who is trusted, and
    /// a dependency's `trusted = true` counts only in a dependency that is itself trusted, so an
    /// untrusted package cannot hand authority on (RFC 0003 §5.2). The root always may.
    pub fn trusted(&self) -> Vec<bool> {
        let mut trusted = vec![false; self.nodes.len()];
        trusted[0] = true;
        let mut changed = true;
        while changed {
            changed = false;
            for (c, edges) in self.edges.iter().enumerate() {
                for (d, e) in self.nodes[c].manifest.dependencies.iter().zip(edges) {
                    if let Ok(n) = *e
                        && trusted[c]
                        && d.trusted
                        && !trusted[n]
                    {
                        trusted[n] = true;
                        changed = true;
                    }
                }
            }
        }
        trusted
    }

    /// The lock entry of node `n` (not the root) for its `path` source.
    pub fn entry(&self, n: usize, trusted: &[bool]) -> LockedPackage {
        let node = &self.nodes[n];
        let mut dependencies: Vec<String> = (node.manifest.dependencies.iter())
            .zip(&self.edges[n])
            .map(|(d, e)| match *e {
                Ok(t) => format!("{} {}", d.name, self.nodes[t].manifest.package.version),
                Err(_) => d.name.clone(),
            })
            .collect();
        dependencies.sort();
        LockedPackage {
            name: node.manifest.package.name.clone(),
            version: node.manifest.package.version.clone(),
            source: format!("path+{}", node.dir),
            checksum: None,
            effects: node.manifest.package.effects.clone().unwrap_or_default(),
            trusted: trusted[n],
            dependencies,
            span: 0..0,
        }
    }

    /// The lock of a graph whose every entry is a `path` entry that was found, or why not: this
    /// release writes no other lock (plan P1).
    pub fn path_lock(&self) -> Result<Lock, String> {
        if self.truncated {
            return Err(format!("more than {MAX_PACKAGES} packages"));
        }
        for (c, edges) in self.edges.iter().enumerate() {
            for (d, e) in self.nodes[c].manifest.dependencies.iter().zip(edges) {
                match e {
                    Ok(_) => {}
                    Err(None) => {
                        return Err(format!("`{}` is not a `path` dependency", d.name));
                    }
                    Err(Some(p)) => return Err(format!("`{}`: {}", d.name, p.describe())),
                }
            }
        }
        let trusted = self.trusted();
        let mut lock = Lock::default();
        for n in 1..self.nodes.len() {
            let entry = self.entry(n, &trusted);
            if lock.get(&entry.name).is_some() {
                return Err(format!("two packages are named `{}`", entry.name));
            }
            lock.packages.push(entry);
        }
        lock.packages.sort_by(|a, b| a.name.cmp(&b.name));
        Ok(lock)
    }
}

impl WalkProblem {
    pub fn describe(&self) -> String {
        match self {
            WalkProblem::Missing { dir } => format!("no sakura.toml in `{dir}`"),
            WalkProblem::Renamed { found } => {
                format!("the package in that directory is named `{found}`")
            }
            WalkProblem::Cycle => "the path names the root package's own directory".to_owned(),
        }
    }
}

fn check_name(m: &Manifest, d: &Dependency) -> Result<(), Option<WalkProblem>> {
    match m.package.name == d.name {
        true => Ok(()),
        false => Err(Some(WalkProblem::Renamed {
            found: m.package.name.clone(),
        })),
    }
}

/// `rel` (relative to `dir`) relative to the root: `join("util", "../b")` is `b`, `join("",
/// "../b")` is `../b`; `None` when it is the root's own directory.
pub fn join(dir: &str, rel: &str) -> Option<String> {
    match dir {
        "" => relative_path(rel),
        _ => relative_path(&format!("{dir}/{rel}")),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn manifest(text: &str) -> Manifest {
        Manifest::parse(text).unwrap()
    }

    fn root(manifest: Manifest) -> Node<()> {
        Node {
            dir: String::new(),
            manifest,
            meta: (),
        }
    }

    #[test]
    fn version_1_is_empty_and_others_are_refused() {
        assert_eq!(
            Lock::parse(&format!("{HEADER}version = 1\n")),
            Ok(Lock::default())
        );
        for (text, at) in [
            ("version = 3\n", "3"),
            ("version = \"2\"\n", "\"2\""),
            ("[[package]]\nname = \"a\"\n", ""),
        ] {
            let e = Lock::parse(text).unwrap_err();
            assert_eq!(&text[e.span.clone()], at, "{text}");
            assert!(e.message.contains("version = 1"), "{}", e.message);
        }
        let e = Lock::parse("version = 2\n[[package]]\nname = \"a\"\n").unwrap_err();
        assert!(
            e.message.contains("missing field `version`"),
            "{}",
            e.message
        );
        let e = Lock::parse("version = 2\nextra = 1\n").unwrap_err();
        assert!(e.message.contains("unknown field `extra`"), "{}", e.message);
        let twice = "version = 2\n[[package]]\nname = \"a\"\nversion = \"1.0.0\"\nsource = \"path+a\"\n[[package]]\nname = \"a\"\nversion = \"1.0.0\"\nsource = \"path+b\"\n";
        assert!(Lock::parse(twice).unwrap_err().message.contains("twice"));
        assert!(Lock::parse("version = \n").is_err());
    }

    /// RFC 0003 §3.1: sorted entries, a `path` source without a checksum; render then parse is
    /// the identity, and the bytes are fixed.
    #[test]
    fn locks_round_trip_byte_for_byte() {
        let lock = Lock {
            packages: vec![
                LockedPackage {
                    name: "util".into(),
                    version: "0.1.0".into(),
                    source: "path+../util".into(),
                    effects: vec!["Clock".into()],
                    dependencies: vec!["fmt 0.2.0".into()],
                    ..Default::default()
                },
                LockedPackage {
                    name: "backoff".into(),
                    version: "0.4.3".into(),
                    source: "registry+https://registry.sakuralang.com".into(),
                    checksum: Some("sha256:3f8a".into()),
                    trusted: true,
                    ..Default::default()
                },
            ],
        };
        let text = lock.render();
        assert_eq!(
            text,
            format!(
                "{HEADER}version = 2\n\n[[package]]\nname = \"backoff\"\nversion = \"0.4.3\"\nsource = \"registry+https://registry.sakuralang.com\"\nchecksum = \"sha256:3f8a\"\neffects = []\ntrusted = true\ndependencies = []\n\n[[package]]\nname = \"util\"\nversion = \"0.1.0\"\nsource = \"path+../util\"\neffects = [\"Clock\"]\ntrusted = false\ndependencies = [\"fmt 0.2.0\"]\n"
            )
        );
        let back = Lock::parse(&text).unwrap();
        assert_eq!(back.render(), text);
        let util = back.get("util").unwrap();
        assert_eq!(util.path(), Some("../util"));
        assert!(text[util.span.clone()].starts_with("[[package]]\nname = \"util\""));
        assert!(text[util.span.clone()].ends_with("dependencies = [\"fmt 0.2.0\"]"));
    }

    /// A diamond over `path` entries, a transitive path relative to its own package, and trust
    /// that only a trusted package can pass on.
    #[test]
    fn path_graphs_walk_and_lock() {
        let mut dirs: BTreeMap<&str, &str> = BTreeMap::from([
            (
                "../a",
                "[package]\nname = \"a\"\nversion = \"1.0.0\"\neffects = [\"Clock\"]\n[dependencies]\nc = { path = \"../c\", trusted = true }\n",
            ),
            (
                "../b",
                "[package]\nname = \"b\"\nversion = \"2.0.0\"\n[dependencies]\nc = { path = \"../c\" }\n",
            ),
            ("../c", "[package]\nname = \"c\"\nversion = \"0.3.0\"\n"),
        ]);
        let app = manifest(
            "[package]\nname = \"app\"\n[dependencies]\nb = { path = \"../b\", trusted = true }\na = { path = \"../x/../a\" }\n",
        );
        let walk = |dirs: &BTreeMap<&str, &str>| {
            Graph::walk(root(app.clone()), &mut |d| {
                dirs.get(d).map(|t| (manifest(t), ()))
            })
        };
        let g = walk(&dirs);
        let names: Vec<_> = (g.nodes.iter())
            .map(|n| n.manifest.package.name.as_str())
            .collect();
        assert_eq!(names, ["app", "b", "a", "c"]);
        // `a` trusts `c`, but `a` is not trusted itself; `b` is, and does not trust `c`.
        assert_eq!(g.trusted(), [true, true, false, false]);
        let text = g.path_lock().unwrap().render();
        assert!(
            text.contains("name = \"a\"\nversion = \"1.0.0\"\nsource = \"path+../a\"\neffects = [\"Clock\"]\ntrusted = false\ndependencies = [\"c 0.3.0\"]\n"),
            "{text}"
        );
        assert!(
            text.contains("name = \"b\"\nversion = \"2.0.0\"\nsource = \"path+../b\"\neffects = []\ntrusted = true\n"),
            "{text}"
        );
        // Trusting `a` passes its trust of `c` on.
        let trusting = manifest(
            "[package]\nname = \"app\"\n[dependencies]\na = { path = \"../a\", trusted = true }\n",
        );
        let g = Graph::walk(root(trusting), &mut |d| {
            dirs.get(d).map(|t| (manifest(t), ()))
        });
        assert_eq!(g.trusted(), [true, true, true]);
        // A missing directory, a renamed package and a registry floor are not path-lockable.
        dirs.remove("../c");
        assert_eq!(
            walk(&dirs).path_lock().unwrap_err(),
            "`c`: no sakura.toml in `../c`"
        );
        dirs.insert("../c", "[package]\nname = \"see\"\n");
        assert!(walk(&dirs).path_lock().unwrap_err().contains("named `see`"));
        let floors = manifest("[package]\nname = \"app\"\n[dependencies]\nhttp = \"1.0.0\"\n");
        let g = Graph::walk(root(floors), &mut |_| None);
        assert_eq!(
            g.path_lock().unwrap_err(),
            "`http` is not a `path` dependency"
        );
        assert_eq!(join("util", "../b").as_deref(), Some("b"));
        assert_eq!(join("", "../b").as_deref(), Some("../b"));
        assert_eq!(join("../util", "..").as_deref(), Some(".."));
        assert_eq!(join("util", ".."), None);
    }
}
